"""Developer tool: derives rough spectral coverage of missions from the UPJS filter table.

Not part of the public API and not imported by the package. It reads ``filters.main``
(Registry record ``ivo://astro.upjs/filters/q/main``, TAP service
``https://skvo.science.upjs.sk/tap``) with ``pyvo`` and writes
``src/lc_discovery/shared/filter_spectral_coverage.py``. For each mission the spectral
interval is the union of the wavelength limits (``wavelength_min`` to ``wavelength_max``) of
the listed filters (plus maintainer-given ranges, ``EXTRA_RANGES_ANGSTROM``), converted to joules (the unit of the Registry ``stc_spectral`` table)
with ``astropy.units.spectral``. Run from the package root::

    python tools/fetch_filter_coverage.py

The values are rough on purpose. Where the filter table has no entry for a survey filter,
the developer chose a stand-in (see ``MISSION_FILTERS``); the stand-ins are written into the
generated module. A listed filter missing in the table stops the tool with an error.

References:
    https://www.ivoa.net/documents/RegTAP/20241002/REC-RegTAP-1.2.html (section 8.17)
"""

from __future__ import annotations

import argparse
import logging
from datetime import date
from pathlib import Path

import pyvo
from astropy import units as u

logger = logging.getLogger(__name__)

TAP_URL = "https://skvo.science.upjs.sk/tap"
OUTPUT_PATH = (
    Path(__file__).resolve().parents[1]
    / "src"
    / "lc_discovery"
    / "shared"
    / "filter_spectral_coverage.py"
)

# mission constant -> (survey bands, stand-in filter ids in filters.main)
MISSION_FILTERS: dict[str, tuple[str, tuple[str, ...]]] = {
    "ASASSN_SPECTRAL": (
        "ASAS-SN V (Bessell V), g (SDSS g)",
        ("Generic/Bessell.V", "SLOAN/SDSS.g"),
    ),
    "ZTF_SPECTRAL": (
        "ZTF g, r, i (SDSS g, r, i)",
        ("SLOAN/SDSS.g", "SLOAN/SDSS.r", "SLOAN/SDSS.i"),
    ),
    "PS1_SPECTRAL": (
        "Pan-STARRS1 g, r, i (SDSS g, r, i) and z, y (limits given by the maintainer)",
        ("SLOAN/SDSS.g", "SLOAN/SDSS.r", "SLOAN/SDSS.i"),
    ),
    "TESS_SPECTRAL": ("TESS", ("TESS/TESS.Red",)),
    "OGLE_SPECTRAL": (
        "OGLE V and I (Bessell V and I)",
        ("Generic/Bessell.V", "Generic/Bessell.I"),
    ),
}

# mission constant -> wavelength ranges (angstrom) given by the maintainer, not in filters.main
EXTRA_RANGES_ANGSTROM: dict[str, tuple[tuple[float, float], ...]] = {
    "PS1_SPECTRAL": ((8030.0, 9350.0), (9100.0, 10878.0)),  # PS1 z, PS1 y
}


def fetch_limits_angstrom(filter_ids: tuple[str, ...], tap_url: str) -> tuple[float, float]:
    """Reads the wavelength limits of filters and returns their union.

    Args:
        filter_ids: Identifiers in ``filters.main`` (``filter_id`` column).
        tap_url: TAP service URL.

    Returns:
        Tuple of the smallest ``wavelength_min`` and the largest ``wavelength_max`` in angstrom.

    Raises:
        ValueError: If a filter is missing from the table.
    """
    quoted = ", ".join("'" + fid.replace("'", "''") + "'" for fid in filter_ids)
    table = (
        pyvo.dal.TAPService(tap_url)
        .run_sync(
            "SELECT filter_id, wavelength_min, wavelength_max FROM filters.main "
            f"WHERE filter_id IN ({quoted})"
        )
        .to_table()
    )
    missing = set(filter_ids) - set(str(v) for v in table["filter_id"])
    if missing:
        raise ValueError(f"filters missing in filters.main: {sorted(missing)}")
    low = (table["wavelength_min"].quantity).to(u.AA).min()
    high = (table["wavelength_max"].quantity).to(u.AA).max()
    return float(low.value), float(high.value)


def to_joules(low_angstrom: float, high_angstrom: float) -> tuple[float, float]:
    """Converts a wavelength range to an energy interval.

    Args:
        low_angstrom: Shortest wavelength in angstrom.
        high_angstrom: Longest wavelength in angstrom.

    Returns:
        Tuple (lower energy, upper energy) in joules, from the longest and shortest wavelength.
    """
    energy_low = (high_angstrom * u.AA).to(u.J, u.spectral())
    energy_high = (low_angstrom * u.AA).to(u.J, u.spectral())
    return float(energy_low.value), float(energy_high.value)


def render_module(entries: dict[str, tuple[str, tuple[str, ...], tuple[float, float]]]) -> str:
    """Renders the content of ``filter_spectral_coverage.py``.

    Args:
        entries: Constant name -> (bands text, filter ids, wavelength range in angstrom).

    Returns:
        Python source text of the module.
    """
    parts = [
        '"""Rough spectral coverage (joules) of missions, from the UPJS filter table.\n\n'
        "Generated by tools/fetch_filter_coverage.py from filters.main (Registry record\n"
        f"ivo://astro.upjs/filters/q/main, {TAP_URL}) on {date.today().isoformat()}.\n"
        "Each value is the union of the wavelength limits of stand-in filters, converted with\n"
        'astropy.units.spectral. Rough information only.\n"""\n'
    ]
    for name, (bands, filter_ids, (low, high)) in entries.items():
        extra = EXTRA_RANGES_ANGSTROM.get(name, ())
        extra_text = "".join(f"; plus {a:.0f} to {b:.0f} angstrom (maintainer)" for a, b in extra)
        e_low, e_high = to_joules(low, high)
        parts.append(
            f"\n# {bands}.\n# Filters: {', '.join(filter_ids)}{extra_text}; union {low:.0f} to {high:.0f} angstrom.\n"
            f"{name} = (({e_low!r}, {e_high!r}),)\n"
        )
    return "".join(parts)


def main() -> None:
    """Command line entry point: reads the filter table and writes the module."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--output", type=Path, default=OUTPUT_PATH)
    parser.add_argument("--tap-url", default=TAP_URL)
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO)
    entries = {}
    for name, (bands, filter_ids) in MISSION_FILTERS.items():
        low, high = fetch_limits_angstrom(filter_ids, args.tap_url)
        for extra_low, extra_high in EXTRA_RANGES_ANGSTROM.get(name, ()):
            low, high = min(low, extra_low), max(high, extra_high)
        limits = (low, high)
        logger.info("%s: %.0f to %.0f angstrom", name, *limits)
        entries[name] = (bands, filter_ids, limits)
    args.output.write_text(render_module(entries), encoding="utf-8")
    logger.info("Wrote %s", args.output)


if __name__ == "__main__":
    main()
