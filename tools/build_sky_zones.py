"""Developer tool: builds the survey sky zones used for spatial coverage (MOC strings).

Not part of the public API and not imported by the package. It writes
``src/lc_discovery/shared/sky_zones.py``, which keeps the zones as IVOA MOC ASCII strings so
that the package itself does not need MOCpy. Used by the ZTF and Pan-STARRS1 providers
(declination above -30 deg). Run from the package root::

    python tools/build_sky_zones.py

Needs ``mocpy`` (not a dependency of the package). Each zone is built with
``MOC.from_zone`` at order 6 (about 1 degree), so a zone reaches a little beyond its nominal
edge. That is the safe direction for a rule that skips a mission only when the target is
explicitly outside the coverage.

Reference: https://www.ivoa.net/documents/MOC/index.html
"""

from __future__ import annotations

import argparse
import logging
import textwrap
from dataclasses import dataclass
from pathlib import Path

from astropy.coordinates import SkyCoord
from mocpy import MOC

logger = logging.getLogger(__name__)

OUTPUT_PATH = (
    Path(__file__).resolve().parents[1] / "src" / "lc_discovery" / "shared" / "sky_zones.py"
)
MOC_ORDER = 6


@dataclass(frozen=True)
class DeclinationZone:
    """A band of the sky between two declinations, all right ascensions.

    Attributes:
        constant: Name of the constant in ``sky_zones.py``.
        dec_min: Lower declination limit in degrees.
        dec_max: Upper declination limit in degrees.
        used_by: Short text naming the surveys, for the comment in the module.
    """

    constant: str
    dec_min: float
    dec_max: float
    used_by: str


ZONES = (DeclinationZone("DEC_ABOVE_MINUS_30_MOC", -30.0, 90.0, "ZTF DR24 and Pan-STARRS1 DR2"),)


def build_zone_moc(zone: DeclinationZone) -> str:
    """Builds the MOC string of a declination band.

    Args:
        zone: The band definition.

    Returns:
        MOC in IVOA ASCII serialisation at ``MOC_ORDER``.
    """
    corners = SkyCoord([[0.0, zone.dec_min], [360.0, zone.dec_max]], unit="deg")
    return MOC.from_zone(corners, max_depth=MOC_ORDER).serialize(format="str")


def render_module(zones: tuple[DeclinationZone, ...]) -> str:
    """Renders the content of ``sky_zones.py``.

    Args:
        zones: Zone definitions to include.

    Returns:
        Python source text of the module.
    """
    parts = [
        '"""Sky zones of survey footprints as IVOA MOC strings (ICRS).\n\n'
        "Generated by tools/build_sky_zones.py with MOCpy (``MOC.from_zone``); the package does\n"
        "not import MOCpy. They are the Registry form of spatial coverage (IVOA VODataService\n"
        '1.2, section 3.2; MOC 2.0).\n"""\n'
    ]
    for zone in zones:
        lines = textwrap.wrap(build_zone_moc(zone), width=86)
        body = "\n".join(
            f'    "{line} "' if i < len(lines) - 1 else f'    "{line}"'
            for i, line in enumerate(lines)
        )
        parts.append(
            f"\n# Declination {zone.dec_min:g} to {zone.dec_max:g} deg, all right ascensions, "
            f"order {MOC_ORDER}.\n# Used by {zone.used_by}. The boundary cells make the zone "
            "reach a little beyond its edge.\n"
            f"{zone.constant} = (\n{body}\n)\n"
        )
    return "".join(parts)


def main() -> None:
    """Command line entry point: builds the zones and writes the module."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--output", type=Path, default=OUTPUT_PATH)
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO)
    args.output.write_text(render_module(ZONES), encoding="utf-8")
    logger.info("Wrote %s (%d zones)", args.output, len(ZONES))


if __name__ == "__main__":
    main()
