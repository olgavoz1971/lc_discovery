"""Developer tool: builds the TESS spatial coverage (a MOC) from the sector pointings.

Not part of the public API and not imported by the package. It uses ``tess-point``
(module ``tess_stars2px``), which holds the pointing table (boresight RA, Dec and roll of
each sector) and the focal-plane model of the four cameras, so no geometry is derived here.
For every sector, camera and CCD the outline of the science pixel area is converted to sky
coordinates (``pix2radec_nocheck_single``) and turned into a MOC polygon; all polygons are
united into one mission-wide MOC and written to ``providers/tess/coverage_data.py``.

Needs ``tess-point`` and ``mocpy`` (not dependencies of the package). Run from the package root::

    python tools/build_tess_coverage.py

Notes:
    * The pointing table of ``tess-point`` is unofficial and includes planned sectors; see
      https://tess.mit.edu/observations/ for the official table.
    * Special pointings with sector numbers of 1000 and above (for example 3I/ATLAS) are
      left out; only the regular sectors are used.
    * The MOC order is 6 (about 55 arcmin cells), so the footprint is slightly larger than the
      real one. That is the safe direction for a rule that skips a mission only when the
      target is explicitly outside the coverage.
"""

from __future__ import annotations

import argparse
import logging
import textwrap
from datetime import date
from pathlib import Path

import numpy as np
from astropy import units as u
from astropy.coordinates import SkyCoord
from mocpy import MOC
from tess_stars2px import TESS_Spacecraft_Pointing_Data

logger = logging.getLogger(__name__)

OUTPUT_PATH = (
    Path(__file__).resolve().parents[1]
    / "src"
    / "lc_discovery"
    / "providers"
    / "tess"
    / "coverage_data.py"
)
MOC_ORDER = 6
CCD_PIXELS = 2048
EDGE_POINTS = 8
MAX_REGULAR_SECTOR = 999


def _ccd_outline() -> np.ndarray:
    """Returns the outline of one CCD science area in pixel coordinates.

    Returns:
        Array of shape ``(4 * EDGE_POINTS, 2)`` with (column, row) pairs, counter-clockwise,
        in the convention of ``pix2radec_nocheck_single`` (science area 0 to 2047).
    """
    edge = np.linspace(0.0, CCD_PIXELS - 1.0, EDGE_POINTS, endpoint=False)
    last = CCD_PIXELS - 1.0
    bottom = np.column_stack([edge, np.zeros(EDGE_POINTS)])
    right = np.column_stack([np.full(EDGE_POINTS, last), edge])
    top = np.column_stack([last - edge, np.full(EDGE_POINTS, last)])
    left = np.column_stack([np.zeros(EDGE_POINTS), last - edge])
    return np.vstack([bottom, right, top, left])


def _ccd_moc(pointing, camera: int, ccd: int, outline: np.ndarray) -> MOC:
    """Builds the MOC of one CCD for one sector pointing.

    Args:
        pointing: ``Levine_FPG`` object of the sector (from ``tess_stars2px``).
        camera: Camera index, 0 to 3.
        ccd: CCD index, 0 to 3.
        outline: Pixel outline from ``_ccd_outline``.

    Returns:
        MOC of the CCD footprint at ``MOC_ORDER``.
    """
    ras, decs = zip(
        *(pointing.pix2radec_nocheck_single(camera, ccd, list(pixel)) for pixel in outline)
    )
    corners = SkyCoord(ra=np.array(ras) * u.deg, dec=np.array(decs) * u.deg, frame="icrs")
    return MOC.from_polygon_skycoord(corners, max_depth=MOC_ORDER)


def build_tess_moc() -> tuple[MOC, list[int]]:
    """Builds the union of all regular TESS sectors, cameras and CCDs.

    Returns:
        Tuple of the united MOC and the list of the sector numbers used.
    """
    pointings = TESS_Spacecraft_Pointing_Data()
    outline = _ccd_outline()
    union = None
    used: list[int] = []
    for index, sector in enumerate(pointings.sectors):
        if int(sector) > MAX_REGULAR_SECTOR:
            logger.info("Skipping special pointing %s", sector)
            continue
        for camera in range(4):
            for ccd in range(4):
                moc = _ccd_moc(pointings.fpgObjs[index], camera, ccd, outline)
                union = moc if union is None else union.union(moc)
        used.append(int(sector))
        logger.debug("Sector %s added", sector)
    if union is None:
        raise ValueError("tess-point returned no regular sectors")
    return union, used


def render_module(moc_string: str, sectors: list[int]) -> str:
    """Renders the content of ``coverage_data.py``.

    Args:
        moc_string: MOC in IVOA ASCII serialisation.
        sectors: Sector numbers the MOC was built from.

    Returns:
        Python source text of the module.
    """
    lines = textwrap.wrap(moc_string, width=86)
    body = "\n".join(
        f'    "{line} "' if i < len(lines) - 1 else f'    "{line}"' for i, line in enumerate(lines)
    )
    return (
        f'"""TESS spatial coverage (all regular sectors), built on {date.today().isoformat()}.\n\n'
        "Generated by tools/build_tess_coverage.py from the sector pointings and the camera\n"
        "focal-plane model of tess-point (sectors "
        f"{min(sectors)} to {max(sectors)}, planned sectors included).\n"
        f"IVOA MOC ASCII serialisation, ICRS, order {MOC_ORDER}.\n"
        '"""\n\n'
        f"TESS_SPATIAL_MOC = (\n{body}\n)\n"
    )


def main() -> None:
    """Command line entry point: builds the MOC and writes the module."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--output", type=Path, default=OUTPUT_PATH)
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO)
    moc, sectors = build_tess_moc()
    moc_string = moc.serialize(format="str")
    args.output.write_text(render_module(moc_string, sectors), encoding="utf-8")
    logger.info(
        "Wrote %s: %d sectors, sky fraction %.3f", args.output, len(sectors), moc.sky_fraction
    )


if __name__ == "__main__":
    main()
